//! `locales/endonyms.json`: each shipped language written in its own name ("Deutsch").
//!
//! Endonyms are data, not translations: the language choice shows the same name in every UI
//! language, so a person who cannot read the current language can still find theirs. Both clients
//! get the list generated from the shipped locale set (web: `generated/locales.ts`, Android:
//! `values/language_choices.xml`), so no client keeps a list of its own.
//!
//! Order of the generated list: `en` first, then the remaining locale tags alphabetically (the
//! order of `Catalogue::tags`). The clients put their translated "match system" entry before it.

use crate::android::escape_text;
use crate::catalogue::Catalogue;
use serde_json::Value;
use std::path::Path;

/// File in `locales/` that is not a catalogue.
pub const ENDONYMS_FILE: &str = "endonyms.json";

#[derive(Debug, Default, Clone, PartialEq)]
pub struct Endonyms(Vec<(String, String)>);

impl Endonyms {
    pub fn parse(json: &str) -> Result<Self, String> {
        let v: Value = serde_json::from_str(json).map_err(|e| e.to_string())?;
        let obj = v.as_object().ok_or("must be an object of tag: name")?;
        let mut out = Vec::new();
        for (tag, name) in obj {
            match name.as_str() {
                Some(n) if !n.trim().is_empty() => out.push((tag.clone(), n.to_string())),
                _ => return Err(format!("\"{tag}\" must be a non-empty string")),
            }
        }
        Ok(Endonyms(out))
    }

    pub fn get(&self, tag: &str) -> Option<&str> {
        self.0
            .iter()
            .find(|(t, _)| t == tag)
            .map(|(_, n)| n.as_str())
    }

    /// Every locale of the catalogue needs a name, and no name may belong to an unknown locale
    /// (a stale entry after a locale was removed).
    pub fn validate(&self, cat: &Catalogue, issues: &mut Vec<String>) {
        let tags = cat.tags();
        for t in &tags {
            if self.get(t).is_none() {
                issues.push(format!("{ENDONYMS_FILE}: no endonym for locale \"{t}\""));
            }
        }
        for (t, _) in &self.0 {
            if !tags.contains(&t.as_str()) {
                issues.push(format!(
                    "{ENDONYMS_FILE}: \"{t}\" is not a locale in locales/ (stale entry?)"
                ));
            }
        }
    }

    /// (tag, endonym) of the given locales, in the given order.
    pub fn of<'a>(&'a self, tags: &[&'a str]) -> Vec<(&'a str, &'a str)> {
        tags.iter()
            .filter_map(|t| self.get(t).map(|n| (*t, n)))
            .collect()
    }
}

pub fn load(dir: &Path, issues: &mut Vec<String>) -> Endonyms {
    let file = dir.join(ENDONYMS_FILE);
    match std::fs::read_to_string(&file)
        .map_err(|e| e.to_string())
        .and_then(|s| Endonyms::parse(&s))
    {
        Ok(e) => e,
        Err(e) => {
            issues.push(format!("cannot read {}: {e}", file.display()));
            Endonyms::default()
        }
    }
}

fn js(s: &str) -> String {
    Value::String(s.to_string()).to_string()
}

/// `generated/locales.ts`: the shipped locales, their endonyms and their bundles for the web
/// client. Locale tags are the file names (`zh-Hans.json`).
pub fn render_web_module(cat: &Catalogue, endonyms: &Endonyms) -> (String, String) {
    let tags = cat.tags();
    let ident = |t: &str| format!("b_{}", t.replace('-', "_"));
    let mut s =
        String::from("// Generated by i18n-gen from locales/ (git-ignored); do not edit.\n");
    for t in &tags {
        s.push_str(&format!("import {} from \"./{t}.json\";\n", ident(t)));
    }
    let list = tags.iter().map(|t| js(t)).collect::<Vec<_>>().join(", ");
    s.push_str(&format!("\nexport const LOCALES = [{list}] as const;\n"));
    s.push_str("export type Locale = (typeof LOCALES)[number];\n\n");
    s.push_str("/** Each language in its own name; the same in every UI language. */\n");
    s.push_str("export const ENDONYMS: Readonly<Record<Locale, string>> = {\n");
    for (t, n) in endonyms.of(&tags) {
        s.push_str(&format!("  {}: {},\n", js(t), js(n)));
    }
    s.push_str("};\n\nexport const GENERATED_BUNDLES = {\n");
    for t in &tags {
        s.push_str(&format!("  {}: {},\n", js(t), ident(t)));
    }
    s.push_str("} as const;\n");
    ("locales.ts".to_string(), s)
}

/// `values/language_choices.xml`: parallel arrays of locale tags and endonyms for the Android
/// language list (not translatable: the names are shown as they are).
pub fn render_android_choices(cat: &Catalogue, endonyms: &Endonyms) -> (String, String) {
    let tags = cat.tags();
    let pairs = endonyms.of(&tags);
    let array = |name: &str, items: Vec<&str>| {
        let mut a = format!("    <string-array name=\"{name}\" translatable=\"false\">\n");
        for i in items {
            a.push_str(&format!("        <item>{}</item>\n", escape_text(i, false)));
        }
        a.push_str("    </string-array>\n");
        a
    };
    let xml = format!(
        "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<!-- Generated by i18n-gen from locales/; do not edit. -->\n<resources>\n{}{}</resources>\n",
        array("language_tags", pairs.iter().map(|(t, _)| *t).collect()),
        array("language_endonyms", pairs.iter().map(|(_, n)| *n).collect()),
    );
    ("values/language_choices.xml".to_string(), xml)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::catalogue::Flat;

    fn cat(tags: &[&str]) -> Catalogue {
        let one: Flat = vec![("a.b".into(), "x".into())];
        Catalogue::new(tags.iter().map(|t| (t.to_string(), one.clone())).collect())
    }

    const NAMES: &str = r#"{"en":"English","de":"Deutsch","zh-Hans":"中文（简体）"}"#;

    #[test]
    fn parse_rejects_non_strings_and_empty_names() {
        assert!(Endonyms::parse(r#"{"en":1}"#).is_err());
        assert!(Endonyms::parse(r#"{"en":" "}"#).is_err());
        assert!(Endonyms::parse("[]").is_err());
        assert!(Endonyms::parse(NAMES).is_ok());
    }

    #[test]
    fn validate_names_missing_and_stale_entries() {
        let e = Endonyms::parse(r#"{"en":"English","fr":"Français"}"#).unwrap();
        let mut issues = Vec::new();
        e.validate(&cat(&["en", "de"]), &mut issues);
        assert_eq!(issues.len(), 2, "{issues:?}");
        assert!(issues.iter().any(|i| i.contains("locale \"de\"")));
        assert!(issues.iter().any(|i| i.contains("\"fr\" is not a locale")));
    }

    #[test]
    fn web_module_lists_locales_in_catalogue_order_with_endonyms() {
        let e = Endonyms::parse(NAMES).unwrap();
        let (name, ts) = render_web_module(&cat(&["en", "de", "zh-Hans"]), &e);
        assert_eq!(name, "locales.ts");
        assert!(ts.contains(r#"export const LOCALES = ["en", "de", "zh-Hans"] as const;"#));
        assert!(ts.contains(r#""zh-Hans": "中文（简体）","#));
        assert!(ts.contains(r#"import b_zh_Hans from "./zh-Hans.json";"#));
        assert!(ts.contains(r#""de": b_de,"#));
    }

    #[test]
    fn android_choices_are_parallel_arrays_in_catalogue_order() {
        let e = Endonyms::parse(NAMES).unwrap();
        let (name, xml) = render_android_choices(&cat(&["en", "de", "zh-Hans"]), &e);
        assert_eq!(name, "values/language_choices.xml");
        let tags = xml.split("language_endonyms").next().unwrap();
        assert!(tags.contains("<item>en</item>") && tags.contains("<item>zh-Hans</item>"));
        assert!(xml.contains("<item>Deutsch</item>"));
        assert!(xml.find("Deutsch").unwrap() < xml.find("中文（简体）").unwrap());
        assert!(xml.contains("translatable=\"false\""));
    }
}
