#[cfg(test)]
mod tests {
    use super::*;
    use crate::lists::tests::good;

    #[test]
    fn web_module_lists_stun_and_the_default_ice_urls() {
        let ts = web_module(&good());
        assert!(ts.contains("export const PUBLIC_STUN_SERVERS"));
        assert!(ts.contains("export const DEFAULT_STUN_URLS"));
        assert!(ts.contains("\"stun:a.example.net:443\""));
        assert!(!ts.contains("RELAYS"));
        assert!(ts.contains("export const PROJECT_SERVER"));
        assert!(ts.contains("\"mailbox\": \"r:gs.example.net/signaling\""));
        assert!(ts.contains("\"status\": \"pending\""));
        assert!(ts.contains("\"live\": false"));
    }

    #[test]
    fn kotlin_object_is_well_formed() {
        let kt = kotlin_object(&good());
        assert!(kt.starts_with("// Generated"));
        assert!(kt.contains("package org.guardedsleep.app.config"));
        assert!(kt.contains("val stunServers: List<PublicStun>"));
        assert!(!kt.contains("PublicRelay"));
        assert!(kt.contains("val defaultStunUrls: List<String>"));
        assert!(kt.contains("val projectServer: ProjectServer"));
        assert!(kt.contains("\"r:gs.example.net/signaling\""));
        assert!(kt.contains("            false,\n        )\n}\n"));
        assert_eq!(kt.matches('(').count(), kt.matches(')').count());
    }

    #[test]
    fn kotlin_strings_are_escaped() {
        assert_eq!(kotlin_string("a\"b\\c$d"), "\"a\\\"b\\\\c\\$d\"");
    }
}
