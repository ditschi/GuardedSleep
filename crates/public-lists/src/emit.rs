//! Generated outputs: a TypeScript module for the web client, a Kotlin object for Android, and the
//! web CSP `connect-src` origins. The core carries none of the data; platforms pass the relay
//! candidates into it (`pick_relays`).

use serde_json::{Value, json};

use crate::lists::Lists;

const BANNER: &str = "Generated by `public-lists` (crates/public-lists) from data/*.json. Do not edit and do not commit; `just gen` and the build regenerate it.";

fn relay_value(r: &crate::lists::Relay) -> Value {
    json!({
        "host": r.host,
        "url": r.url(),
        "operator": r.operator,
        "hoster": r.hoster,
        "country": r.country,
        "privacyPolicy": r.privacy_policy,
        "lastVetted": r.last_vetted,
    })
}

fn stun_value(s: &crate::lists::Stun) -> Value {
    json!({
        "host": s.host,
        "port": s.port,
        "url": s.url(),
        "operator": s.operator,
        "country": s.country,
        "privacyPolicy": s.privacy_policy,
        "lastVetted": s.last_vetted,
    })
}

fn pretty(value: &Value) -> String {
    serde_json::to_string_pretty(value).unwrap_or_else(|_| "[]".into())
}

/// `public-lists.ts`: typed constants. Values are JSON, which is valid TypeScript.
pub fn web_module(lists: &Lists) -> String {
    let relays: Vec<Value> = lists.active_relays().map(relay_value).collect();
    let stun: Vec<Value> = lists.active_stun().map(stun_value).collect();
    let ice: Vec<Value> = lists
        .default_ice_stun()
        .iter()
        .map(|s| Value::String(s.url()))
        .collect();
    format!(
        "// {BANNER}\n\n\
export interface PublicRelay {{\n  readonly host: string;\n  /** Always `wss://<host>`. */\n  readonly url: string;\n  readonly operator: string;\n  readonly hoster: string | null;\n  readonly country: string;\n  readonly privacyPolicy: string | null;\n  readonly lastVetted: string;\n}}\n\n\
export interface PublicStun {{\n  readonly host: string;\n  readonly port: number;\n  /** `stun:<host>:<port>`. */\n  readonly url: string;\n  readonly operator: string;\n  readonly country: string;\n  readonly privacyPolicy: string | null;\n  readonly lastVetted: string;\n}}\n\n\
/** Curated Nostr relays, one per operator. */\nexport const PUBLIC_NOSTR_RELAYS: readonly PublicRelay[] = {};\n\n\
/** Curated STUN servers. */\nexport const PUBLIC_STUN_SERVERS: readonly PublicStun[] = {};\n\n\
/** The STUN URLs of a default install: every entry of the first two distinct operators. */\nexport const DEFAULT_STUN_URLS: readonly string[] = {};\n",
        pretty(&Value::Array(relays)),
        pretty(&Value::Array(stun)),
        pretty(&Value::Array(ice)),
    )
}

fn kotlin_string(text: &str) -> String {
    // Validated text has no quote, backslash or dollar; escape anyway so the output stays valid.
    let mut out = String::from("\"");
    for c in text.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '$' => out.push_str("\\$"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

fn kotlin_opt(text: Option<&str>) -> String {
    text.map_or_else(|| "null".into(), kotlin_string)
}

/// `PublicLists.kt` in package `org.guardedsleep.app.config`.
pub fn kotlin_object(lists: &Lists) -> String {
    let mut out = format!(
        "// {BANNER}\npackage org.guardedsleep.app.config\n\n\
/** A curated public Nostr relay (always `wss://host`). */\n\
data class PublicRelay(\n    val host: String,\n    val url: String,\n    val operator: String,\n    val hoster: String?,\n    val country: String,\n    val privacyPolicy: String?,\n    val lastVetted: String,\n)\n\n\
/** A curated public STUN server. */\n\
data class PublicStun(\n    val host: String,\n    val port: Int,\n    val url: String,\n    val operator: String,\n    val country: String,\n    val privacyPolicy: String?,\n    val lastVetted: String,\n)\n\n\
object PublicLists {{\n    /** Curated Nostr relays, one per operator. */\n    val nostrRelays: List<PublicRelay> =\n        listOf(\n"
    );
    for r in lists.active_relays() {
        out.push_str(&format!(
            "            PublicRelay(\n                {},\n                {},\n                {},\n                {},\n                {},\n                {},\n                {},\n            ),\n",
            kotlin_string(&r.host),
            kotlin_string(&r.url()),
            kotlin_string(&r.operator),
            kotlin_opt(r.hoster.as_deref()),
            kotlin_string(&r.country),
            kotlin_opt(r.privacy_policy.as_deref()),
            kotlin_string(&r.last_vetted),
        ));
    }
    out.push_str("        )\n\n    /** Curated STUN servers. */\n    val stunServers: List<PublicStun> =\n        listOf(\n");
    for s in lists.active_stun() {
        out.push_str(&format!(
            "            PublicStun(\n                {},\n                {},\n                {},\n                {},\n                {},\n                {},\n                {},\n            ),\n",
            kotlin_string(&s.host),
            s.port,
            kotlin_string(&s.url()),
            kotlin_string(&s.operator),
            kotlin_string(&s.country),
            kotlin_opt(s.privacy_policy.as_deref()),
            kotlin_string(&s.last_vetted),
        ));
    }
    out.push_str("        )\n\n    /** The STUN URLs of a default install: every entry of the first two distinct operators. */\n    val defaultStunUrls: List<String> =\n        listOf(\n");
    for s in lists.default_ice_stun() {
        out.push_str(&format!("            {},\n", kotlin_string(&s.url())));
    }
    out.push_str("        )\n}\n");
    out
}

/// `relay-origins.json`: `{"origins": ["wss://host", ...]}` for the web CSP `connect-src`.
pub fn csp_origins(lists: &Lists) -> String {
    let origins: Vec<Value> = lists
        .active_relays()
        .map(|r| Value::String(r.url()))
        .collect();
    format!("{}\n", pretty(&json!({ "origins": origins })))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::lists::tests::good;

    #[test]
    fn web_module_lists_relays_stun_and_the_default_ice_urls() {
        let ts = web_module(&good());
        assert!(ts.contains("export const PUBLIC_NOSTR_RELAYS"));
        assert!(ts.contains("\"url\": \"wss://r1.example.net\""));
        assert!(ts.contains("export const DEFAULT_STUN_URLS"));
        assert!(ts.contains("\"stun:a.example.net:443\""));
        assert!(ts.contains("\"hoster\": null"));
    }

    #[test]
    fn kotlin_object_is_well_formed() {
        let kt = kotlin_object(&good());
        assert!(kt.starts_with("// Generated"));
        assert!(kt.contains("package org.guardedsleep.app.config"));
        assert!(kt.contains("val nostrRelays: List<PublicRelay>"));
        assert!(kt.contains("\"wss://r6.example.net\""));
        assert!(kt.contains("val defaultStunUrls: List<String>"));
        assert_eq!(kt.matches('(').count(), kt.matches(')').count());
    }

    #[test]
    fn kotlin_strings_are_escaped() {
        assert_eq!(kotlin_string("a\"b\\c$d"), "\"a\\\"b\\\\c\\$d\"");
    }

    #[test]
    fn csp_origins_are_wss_origins_of_active_relays() {
        let mut l = good();
        l.relays[0].status = crate::lists::Status::Suspended;
        let json: Value = serde_json::from_str(&csp_origins(&l)).unwrap();
        let origins: Vec<&str> = json["origins"]
            .as_array()
            .unwrap()
            .iter()
            .map(|v| v.as_str().unwrap())
            .collect();
        assert_eq!(origins.len(), 5);
        assert!(!origins.contains(&"wss://r1.example.net"));
        assert!(origins.iter().all(|o| o.starts_with("wss://")));
    }
}
