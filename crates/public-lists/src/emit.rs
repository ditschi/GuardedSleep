//! Generated outputs: a TypeScript module for the web client and a Kotlin object for Android. The
//! core carries none of the data.

use serde_json::Value;
use serde_json::json;

use crate::lists::{Lists, ProjectServer};

const BANNER: &str = "Generated by `public-lists` (crates/public-lists) from data/*.json. Do not edit and do not commit; `just gen` and the build regenerate it.";

fn stun_value(s: &crate::lists::Stun) -> Value {
    json!({
        "host": s.host,
        "port": s.port,
        "url": s.url(),
        "operator": s.operator,
        "country": s.country,
        "privacyPolicy": s.privacy_policy,
        "lastVetted": s.last_vetted,
    })
}

fn project_value(p: &ProjectServer) -> Value {
    json!({
        "host": p.host,
        "path": p.path,
        "mailbox": p.mailbox(),
        "operator": p.operator,
        "country": p.country,
        "hoster": p.hoster,
        "privacyPolicy": p.privacy_policy,
        "imprint": p.imprint,
        "lastVetted": p.last_vetted,
        "status": p.status.as_str(),
        "live": p.is_live(),
    })
}

fn pretty(value: &Value) -> String {
    serde_json::to_string_pretty(value).unwrap_or_else(|_| "[]".into())
}

/// `public-lists.ts`: typed constants. Values are JSON, which is valid TypeScript.
pub fn web_module(lists: &Lists) -> String {
    let stun: Vec<Value> = lists.active_stun().map(stun_value).collect();
    let ice: Vec<Value> = lists
        .default_ice_stun()
        .iter()
        .map(|s| Value::String(s.url()))
        .collect();
    format!(
        "// {BANNER}\n\n\
    export interface PublicStun {{\n  readonly host: string;\n  readonly port: number;\n  /** `stun:<host>:<port>`. */\n  readonly url: string;\n  readonly operator: string;\n  readonly country: string;\n  readonly privacyPolicy: string | null;\n  readonly lastVetted: string;\n}}\n\n\
    export interface ProjectServer {{\n  readonly host: string;\n  /** WebSocket path of the signaling endpoint. */\n  readonly path: string;\n  /** The default mailbox entry, `r:<host><path>`. */\n  readonly mailbox: string;\n  readonly operator: string;\n  readonly country: string;\n  readonly hoster: string;\n  readonly privacyPolicy: string | null;\n  readonly imprint: string | null;\n  readonly lastVetted: string;\n  readonly status: \"pending\" | \"live\";\n  readonly live: boolean;\n}}\n\n\
    /** Curated STUN servers. */\nexport const PUBLIC_STUN_SERVERS: readonly PublicStun[] = {};\n\n\
    /** The STUN URLs of a default install: every entry of the first two distinct operators. */\nexport const DEFAULT_STUN_URLS: readonly string[] = {};\n\n\
    /** The project's own signaling server (`data/project-server.json`). Release builds keep it off while `live` is false. */\nexport const PROJECT_SERVER: ProjectServer = {};\n",
        pretty(&Value::Array(stun)),
        pretty(&Value::Array(ice)),
        pretty(&project_value(&lists.project)),
    )
}

fn kotlin_string(text: &str) -> String {
    // Validated text has no quote, backslash or dollar; escape anyway so the output stays valid.
    let mut out = String::from("\"");
    for c in text.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '$' => out.push_str("\\$"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

fn kotlin_opt(text: Option<&str>) -> String {
    text.map_or_else(|| "null".into(), kotlin_string)
}

