#!/usr/bin/env bash
# Measures this machine once and writes the git-ignored .cache/machine-profile.env that the slot
# semaphore (scripts/lib/slot.sh) reads. Rules and rationale: AGENTS.md section 10.1.
#   scripts/lib/machine-profile.sh           # re-detect only when the file is missing or the hostname differs
#   scripts/lib/machine-profile.sh --force   # re-detect unconditionally
# Environment variables with the same names (GS_CORES, GS_RAM_GB, GS_KVM, GS_MEDIUM_SLOTS,
# GS_HEAVY_SLOTS) override the measured values when the file is written and when slot.sh reads it.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
FILE="$ROOT/.cache/machine-profile.env"
HOST="$(hostname)"

if [ "${1:-}" != "--force" ] && [ -f "$FILE" ] && grep -qx "GS_PROFILE_HOST=$HOST" "$FILE"; then
  exit 0
fi

cores="${GS_CORES:-$(nproc)}"
ram_gb="${GS_RAM_GB:-$(awk '/^MemTotal:/ { printf "%d", $2 / 1048576 + 0.5 }' /proc/meminfo)}"
if [ -n "${GS_KVM:-}" ]; then
  kvm="$GS_KVM"
elif [ -r /dev/kvm ] && [ -w /dev/kvm ]; then
  kvm=1
else
  kvm=0
fi
docker_mode=none
if command -v docker >/dev/null 2>&1; then
  if docker info -f '{{.SecurityOptions}}' 2>/dev/null | grep -q rootless; then
    docker_mode=rootless
  elif docker info >/dev/null 2>&1; then
    docker_mode=rootful
  fi
fi

min() { if [ "$1" -lt "$2" ]; then echo "$1"; else echo "$2"; fi; }
at_least_one() { if [ "$1" -lt 1 ]; then echo 1; else echo "$1"; fi; }
medium="${GS_MEDIUM_SLOTS:-$(at_least_one "$(min $((cores / 4)) $((ram_gb / 6)))")}"
heavy="${GS_HEAVY_SLOTS:-$(at_least_one "$(min $((cores / 8)) $((ram_gb / 12)))")}"

mkdir -p "$ROOT/.cache"
tmp="$(mktemp "$FILE.XXXXXX")"
cat >"$tmp" <<PROFILE
# Machine profile, generated by scripts/lib/machine-profile.sh (see AGENTS.md section 10.1). Do not edit;
# override with environment variables or re-run 'just machine-profile --force'.
GS_PROFILE_HOST=$HOST
GS_CORES=$cores
GS_RAM_GB=$ram_gb
GS_KVM=$kvm
GS_DOCKER=$docker_mode
GS_MEDIUM_SLOTS=$medium
GS_HEAVY_SLOTS=$heavy
GS_PROFILE_TIME=$(date -u +%Y-%m-%dT%H:%M:%SZ)
PROFILE
mv "$tmp" "$FILE"
echo "machine profile: $cores cores, ${ram_gb} GB, kvm=$kvm, docker=$docker_mode, medium=$medium, heavy=$heavy" >&2
