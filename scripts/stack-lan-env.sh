#!/usr/bin/env bash
# Detect the host machine's LAN IPv4 and write docker/stack/.env for phone/tablet testing.
# Usage (from repository root):
#   ./scripts/stack-lan-env.sh           # write docker/stack/.env
#   ./scripts/stack-lan-env.sh --dry-run # print values only
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="$ROOT/docker/stack/.env"

WEB_PORT="${WEB_PORT:-8080}"
WEB_HTTPS_PORT="${WEB_HTTPS_PORT:-8443}"
SIGNALING_PORT="${SIGNALING_PORT:-8787}"
SIGNALING_INTERNAL_PORT="${SIGNALING_INTERNAL_PORT:-8787}"

DRY_RUN=false

usage() {
  cat <<'EOF'
Usage: scripts/stack-lan-env.sh [--dry-run]

Writes docker/stack/.env with the host LAN IPv4 so phones on the same Wi-Fi can reach
the local Docker signaling stack (wss://<LAN-IP>:8443/signaling).

Environment overrides (optional): WEB_PORT, WEB_HTTPS_PORT, SIGNALING_PORT
EOF
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --dry-run)
      DRY_RUN=true
      shift
      ;;
    -h | --help)
      usage
      exit 0
      ;;
    *)
      echo "Unknown argument: $1" >&2
      usage >&2
      exit 1
      ;;
  esac
done

is_ipv4() {
  local ip="$1"
  [[ "$ip" =~ ^([0-9]{1,3}\.){3}[0-9]{1,3}$ ]] || return 1
  local o
  IFS=. read -r o1 o2 o3 o4 <<<"$ip"
  for o in "$o1" "$o2" "$o3" "$o4"; do
    [[ "$o" -ge 0 && "$o" -le 255 ]] || return 1
  done
  return 0
}

detect_lan_ipv4() {
  local ip=""

  if command -v ip >/dev/null 2>&1; then
    ip="$(ip -4 route get 1.1.1.1 2>/dev/null | awk '{for (i = 1; i <= NF; i++) if ($i == "src") { print $(i + 1); exit }}')"
  fi

  if [[ -z "$ip" ]] && command -v hostname >/dev/null 2>&1; then
    ip="$(hostname -I 2>/dev/null | awk '{ print $1 }')"
  fi

  if [[ -z "$ip" ]] && command -v ipconfig >/dev/null 2>&1; then
    local iface
    for iface in en0 en1 eth0; do
      ip="$(ipconfig getifaddr "$iface" 2>/dev/null || true)"
      [[ -n "$ip" ]] && break
    done
  fi

  if ! is_ipv4 "$ip"; then
    echo "Could not detect a LAN IPv4 address on this host." >&2
    echo "Set docker/stack/.env manually (see docker/stack/.env.example)." >&2
    exit 1
  fi

  if [[ "$ip" == 127.* ]]; then
    echo "Detected loopback address ($ip) only; connect a LAN/Wi-Fi interface and retry." >&2
    exit 1
  fi

  echo "$ip"
}

LAN_IP="$(detect_lan_ipv4)"

VITE_SIGNALING_URL="wss://${LAN_IP}:${WEB_HTTPS_PORT}/signaling"
SIGNALING_ALLOWED_ORIGINS="http://127.0.0.1:${WEB_PORT},http://localhost:${WEB_PORT},https://127.0.0.1:${WEB_HTTPS_PORT},https://localhost:${WEB_HTTPS_PORT},http://${LAN_IP}:${WEB_PORT},https://${LAN_IP}:${WEB_HTTPS_PORT}"
VITE_DEV_CONNECT_HINTS=true
TLS_EXTRA_SAN="IP:${LAN_IP}"

ENV_CONTENT="# Generated by scripts/stack-lan-env.sh — re-run: just stack-lan
# Host LAN IP: ${LAN_IP}
WEB_PORT=${WEB_PORT}
WEB_HTTPS_PORT=${WEB_HTTPS_PORT}
TLS_EXTRA_SAN=${TLS_EXTRA_SAN}
SIGNALING_PORT=${SIGNALING_PORT}
SIGNALING_INTERNAL_PORT=${SIGNALING_INTERNAL_PORT}
VITE_SIGNALING_URL=${VITE_SIGNALING_URL}
SIGNALING_ALLOWED_ORIGINS=${SIGNALING_ALLOWED_ORIGINS}
"

if [[ "$DRY_RUN" == true ]]; then
  printf '%s' "$ENV_CONTENT"
  echo "---"
  echo "PWA (phone):  https://${LAN_IP}:${WEB_HTTPS_PORT}/"
  echo "Signaling URL: ${VITE_SIGNALING_URL}"
  exit 0
fi

printf '%s' "$ENV_CONTENT" >"$ENV_FILE"

echo "Wrote ${ENV_FILE}"
echo "  LAN IP:          ${LAN_IP}"
echo "  Open on phone:   https://${LAN_IP}:${WEB_HTTPS_PORT}/"
echo "  Signaling (WSS): ${VITE_SIGNALING_URL}"
echo ""
echo "Next: just stack-up   (or just stack-lan to regenerate .env and start)"
